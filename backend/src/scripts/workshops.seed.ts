async function seedWorkshops(): Promise<void> {
  const mongoUri = process.env.MONGODB_URI;

  if (!mongoUri) {
    throw new Error('La variable MONGODB_URI no está definida.');
  }

  try {
    await mongoose.connect(mongoUri);

    await WorkshopModel.deleteMany({});
    const insertedWorkshops = await WorkshopModel.insertMany(workshops, {
      ordered: true,
    });

    console.log(
      `Seed completado: ${insertedWorkshops.length} talleres insertados.`,
    );
  } catch (error) {
    console.error('Error al ejecutar el seed de talleres:', error);
    process.exitCode = 1;
  } finally {
    await mongoose.disconnect();
  }
}

